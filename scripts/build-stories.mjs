/**
 * Writes stories/<name>.stories.tsx for every item that has a docs-site demo (site/demos/<name>.tsx), grouped by its
 * registry category. Components land under "Components/<Category>/<Title>", blocks under "Blocks/<Title>". Each file
 * has a Default story (the live preview, with controls) and, when the demo has examples, an Examples story.
 *
 *   npm run build:stories    regenerate (also run by `npm run storybook`)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "stories");
const registry = JSON.parse(fs.readFileSync(path.join(root, "registry.json"), "utf8"));

const CATEGORY = { inputs: "Inputs", data: "Data", actions: "Actions", disclosure: "Disclosure", feedback: "Feedback", text: "Text", special: "Special" };
const quote = value => JSON.stringify(value);

for (const file of fs.readdirSync(out)) if (file.endsWith(".stories.tsx")) fs.rmSync(path.join(out, file));

let count = 0;
for (const item of registry.items) {
  const demoPath = path.join(root, "site", "demos", `${item.name}.tsx`);
  if (!fs.existsSync(demoPath)) continue;
  const demoSource = fs.readFileSync(demoPath, "utf8");
  const block = item.type === "registry:block" || item.categories?.[0] === "blocks";
  const group = block ? "Blocks" : `Components/${CATEGORY[item.categories?.[0]] ?? "Other"}`;
  const hasExamples = /\bexamples\s*:\s*\[/.test(demoSource);
  const fill = /layout\s*:\s*"fill"/.test(demoSource) || block;
  const story = `// Generated by scripts/build-stories.mjs from site/demos/${item.name}.tsx. Do not edit; change the demo instead.
import type { Meta, StoryObj } from "@storybook/nextjs-vite";
import demo from "../site/demos/${item.name}";
import { ${hasExamples ? "DemoExamples, " : ""}DemoPreview } from "./demo";

const meta: Meta = {
  title: ${quote(`${group}/${item.title}`)},
  component: demo.component as Meta["component"],
  args: (demo.props ?? {}) as Meta["args"],
  parameters: {
    layout: ${quote(fill ? "padded" : "centered")},
    docs: { description: { component: ${quote(`${item.description} Live docs: ${item.docs?.replace(/^Docs and live preview: /, "") ?? ""}`)} } },
  },
};
export default meta;

export const Default: StoryObj = {
  render: args => <DemoPreview demo={demo as never} args={args} />,
};
${hasExamples ? `
export const Examples: StoryObj = {
  parameters: { layout: "padded", controls: { disable: true } },
  render: () => <DemoExamples demo={demo as never} />,
};
` : ""}`;
  fs.writeFileSync(path.join(out, `${item.name}.stories.tsx`), story);
  count++;
}
console.log(`Wrote ${count} story files into stories/`);
