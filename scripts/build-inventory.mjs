/**
 * The component inventory: every component and block, its category, status, variants (read from its props), the
 * components it is built from, and where to see it. Written to docs/inventory.md (for people and AI agents) and
 * stories/inventory.json (the Storybook "Inventory" page), so it is never edited by hand and never goes stale.
 *
 *   npm run build:inventory
 *
 * Status lives in registry.json `meta.status`: "experimental" (in Storybook, published but not for production) or
 * "stable". A missing status counts as stable (everything that existed before the process).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(fs.readFileSync(path.join(root, "registry.json"), "utf8"));
// A "blocks" category item that lives in registry/components ships in the npm package: a larger component, a composite.
const CATEGORY = { inputs: "Inputs", data: "Data", actions: "Actions", disclosure: "Disclosure", feedback: "Feedback", text: "Text", special: "Special", blocks: "Composites" };

/** Props whose type is a union of string literals (directly or through a local type alias): the variants. */
function variantsOf(file) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
  const aliases = new Map();
  const literals = node => ts.isUnionTypeNode(node) && node.types.every(t => ts.isLiteralTypeNode(t) && ts.isStringLiteral(t.literal))
    ? node.types.map(t => t.literal.text) : null;
  source.forEachChild(node => {
    if (ts.isTypeAliasDeclaration(node)) { const values = literals(node.type); if (values) aliases.set(node.name.text, values); }
  });
  const found = {};
  source.forEachChild(node => {
    if (!ts.isInterfaceDeclaration(node) || !/Props$/.test(node.name.text) || !node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) return;
    for (const member of node.members) {
      if (!ts.isPropertySignature(member) || !member.type || !member.name) continue;
      const name = member.name.getText(source);
      const values = literals(member.type) ?? (ts.isTypeReferenceNode(member.type) ? aliases.get(member.type.typeName.getText(source)) : null);
      if (values && values.length > 1) found[name] = values;
    }
  });
  return found;
}

const rows = [];
for (const item of registry.items) {
  if (item.categories?.[0] === "foundation") continue;
  // A block is copied into an app (registry/blocks); everything in registry/components installs from npm.
  const block = item.files.some(file => file.path.startsWith("registry/blocks/"));
  const main = item.files.find(file => /\.tsx$/.test(file.path) && file.path.includes(`/${item.name}/`)) ?? item.files.find(file => /\.tsx$/.test(file.path));
  if (!main) continue;
  const mainPath = path.join(root, main.path);
  const source = fs.readFileSync(mainPath, "utf8");
  const composes = [...new Set([...source.matchAll(/from "@\/registry\/components\/([\w-]+)\//g)].map(m => m[1]).filter(name => name !== item.name))];
  const category = CATEGORY[item.categories?.[0]] ?? "Other";
  rows.push({
    name: item.name,
    title: item.title,
    kind: block ? "block" : "component",
    category,
    status: item.meta?.status ?? "stable",
    experimentalParts: item.meta?.experimental ?? [],
    description: item.description,
    variants: variantsOf(mainPath),
    composes,
    import: block ? `npx shadcn@latest add @silicon-ui/${item.name}` : `@teamofsilicons/silicon-ui/${item.name}`,
    docs: `https://ui.teamofsilicons.com/${item.name}`,
    storybook: `${block ? "blocks" : `components-${category.toLowerCase()}`}-${item.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}--default`,
  });
}
// Components first (by category), then blocks.
rows.sort((a, b) => (a.kind === "block") - (b.kind === "block") || a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

fs.writeFileSync(path.join(root, "stories", "inventory.json"), `${JSON.stringify(rows, null, 2)}\n`);

const count = (kind, status) => rows.filter(r => r.kind === kind && (!status || r.status === status)).length;
const lines = [
  "# Component inventory",
  "",
  "Generated by `npm run build:inventory` from `registry.json` and each component's props. Do not edit by hand.",
  "Before asking for a new component or variant, check here: what you need may exist, or be a variant of something",
  "that does (see [new-components.md](new-components.md)).",
  "",
  `**${count("component")} components** (${count("component", "stable")} stable, ${count("component", "experimental")} experimental) and **${count("block")} blocks**.`,
  "",
];
let section = "";
for (const row of rows) {
  const heading = row.kind === "block" ? "Blocks" : row.category;
  if (heading !== section) {
    section = heading;
    lines.push(`## ${heading}`, "", "| Component | Status | Variants | Built from | |", "| --- | --- | --- | --- | --- |");
  }
  const variants = Object.entries(row.variants).map(([prop, values]) => `\`${prop}\`: ${values.join(", ")}`).join("<br>") || "—";
  const composes = row.composes.join(", ") || "—";
  const status = row.experimentalParts.length ? `${row.status}; new parts experimental: ${row.experimentalParts.map(name => `\`${name}\``).join(", ")}` : row.status;
  lines.push(`| **${row.title}** \`${row.name}\`<br>${row.description} | ${status} | ${variants} | ${composes} | [docs](${row.docs}) |`);
  const next = rows[rows.indexOf(row) + 1];
  if (!next || (next.kind === "block" ? "Blocks" : next.category) !== section) lines.push("");
}
fs.writeFileSync(path.join(root, "docs", "inventory.md"), `${lines.join("\n")}\n`);
console.log(`Inventory: ${rows.length} items (${count("component")} components, ${count("block")} blocks) in docs/inventory.md and stories/inventory.json`);
